"""gentokens.py writes ui/tokens_gen.go from docs/ui/tokens.json, the design
tokens measured off T3 Code's own web UI (see docs/ui/01-tokens.md).

    python3 tools/t3ui/gentokens.py ../docs/ui/tokens.json ../docs/ui/tokens.extra.json | gofmt > ui/tokens_gen.go

Every custom property whose value is a colour in both themes becomes a
Palette field named after it (--sidebar-row-hover is SidebarRowHover), and
every length becomes a dp value in Metrics. Tailwind's palette (--color-*)
goes in a map, for the components that use its colours directly. Scopes
that restyle a subtree (the sidebar's [data-app-sidebar], the composer's
[data-slot=composer-shell]) become whole palettes too: the theme's, with the
scope's overrides.
"""
import json
import re
import sys

doc = json.load(open(sys.argv[1]))
extra = json.load(open(sys.argv[2])) if len(sys.argv) > 2 else {}
themes = doc["themes"]
light, dark = themes["light"], themes["dark"]


def camel(name):
    parts = re.split(r"[^A-Za-z0-9]+", name.lstrip("-"))
    out = "".join(p[:1].upper() + p[1:] for p in parts if p)
    return ("T" + out) if out[:1].isdigit() else out


HEX = re.compile(r"^#([0-9a-fA-F]{6})([0-9a-fA-F]{2})?$")


def color(v):
    """A resolved value as a Go color.NRGBA literal, or None."""
    if not isinstance(v, str):
        return None
    v = v.strip()
    if v == "transparent":
        return "color.NRGBA{}"
    m = HEX.match(v)
    if not m:
        return None
    rgb, a = m.group(1), m.group(2) or "ff"
    r, g, b = rgb[0:2], rgb[2:4], rgb[4:6]
    return f"color.NRGBA{{R: 0x{r}, G: 0x{g}, B: 0x{b}, A: 0x{a}}}"


def px(v):
    if isinstance(v, (int, float)):
        return float(v)
    m = re.match(r"^(-?[\d.]+)px$", str(v).strip())
    return float(m.group(1)) if m else None


def value(entry):
    return entry.get("value") if isinstance(entry, dict) else entry


def raw(entry):
    r = entry.get("raw", "") if isinstance(entry, dict) else ""
    return " ".join(str(r).split())[:90]


names = sorted(set(light) | set(dark))
palette, metrics, tailwind = [], [], []
for n in names:
    le, de = light.get(n, dark.get(n)), dark.get(n, light.get(n))
    lc, dc = color(value(le)), color(value(de))
    if n.startswith("--color-"):
        if lc:
            tailwind.append((n[len("--color-"):], lc))
        continue
    if lc and dc:
        palette.append((camel(n), n, lc, dc, raw(le)))
        continue
    lp = px(value(le))
    if lp is not None and px(value(de)) == lp:
        metrics.append((camel(n), n, lp, raw(le)))

seen = set()
palette = [p for p in palette if not (p[0] in seen or seen.add(p[0]))]


def num(f):
    return ("%g" % f) if f != int(f) else str(int(f))


out = [
    f"// Code generated by tools/t3ui/gentokens.py from docs/ui/tokens.json ({doc.get('tag', '')}). DO NOT EDIT.",
    "",
    "package ui",
    "",
    'import "image/color"',
    "",
    "// Palette is T3 Code's colour tokens for one theme, named after its CSS",
    "// custom properties: --sidebar-row-hover is SidebarRowHover.",
    "type Palette struct {",
]
out += [f"\t{f} color.NRGBA // {n}: {r}" for f, n, _, _, r in palette]
out += ["}", ""]
for title, idx in (("T3Light", 2), ("T3Dark", 3)):
    out.append(f"// {title} is T3's {'light' if idx == 2 else 'dark'} theme, as its web UI renders it.")
    out.append(f"var {title} = Palette{{")
    out += [f"\t{p[0]}: {p[idx]}," for p in palette]
    out += ["}", ""]
SCOPES = {"[data-app-sidebar]": "Sidebar", "[data-slot=composer-shell]": "Composer"}
fields = {n: i for i, (_, n, _, _, _) in enumerate(palette)}
for sel, suffix in SCOPES.items():
    scope = extra.get("scopes", {}).get(sel)
    if not scope:
        continue
    for title, theme, idx in (("T3Light", "light", 2), ("T3Dark", "dark", 3)):
        over = {}
        for n, e in scope.get(theme, {}).items():
            c = color(value(e))
            if n in fields and c and c != palette[fields[n]][idx]:
                over[n] = c
        out.append(f"// {title}{suffix} is {title} inside {sel}, which restyles it.")
        out.append(f"var {title}{suffix} = Palette{{")
        out += [f"\t{p[0]}: {over.get(p[1], p[idx])}," for p in palette]
        out += ["}", ""]
out += [
    "// Metrics is T3's lengths in dp (one CSS pixel is one dp).",
    "var Metrics = struct {",
]
out += [f"\t{f} float32 // {n}: {r}" for f, n, _, r in metrics]
out += ["}{"]
out += [f"\t{f}: {num(v)}," for f, _, v, _ in metrics]
out += ["}", ""]
out += [
    "// Tailwind is the colour palette T3's components use directly, such as",
    '// Tailwind["emerald-500"].',
    "var Tailwind = map[string]color.NRGBA{",
]
out += [f'\t"{k}": {c},' for k, c in sorted(tailwind)]
out += ["}", ""]
print("\n".join(out))
