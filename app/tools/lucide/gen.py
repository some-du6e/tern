"""Copies the lucide icons T3 uses out of its web client into ui/lucide.go.

Lucide icons are 24x24 outlines stroked 2 wide with round ends. Every shape
becomes SVG path data, which LucideW strokes.

    python3 tools/lucide/gen.py <t3 client assets dir> > ui/lucide.go
"""
import pathlib
import re
import sys

LUCIDE = ["settings", "server", "laptop", "monitor", "circle-user", "git-branch",
          "folder", "lock", "lock-open", "square-menu", "sparkles", "panel-bottom", "panel-right",
          "terminal", "globe", "arrow-left", "arrow-right", "rotate-cw", "plus", "x",
          "panel-left", "panel-left-close", "maximize-2", "minimize-2", "check", "chevron-right",
          "chevron-down", "loader-circle", "square-pen", "search", "list-filter", "folder-plus",
          "git-pull-request", "chart-no-axes-column", "pin", "archive", "trash-2", "clock",
          "copy", "refresh-cw", "wifi-off", "circle-alert", "info", "circle-check", "triangle-alert"]

assets = pathlib.Path(sys.argv[1])
bundle = "\n".join(p.read_text(errors="replace") for p in assets.glob("*.js"))


def num(v):
    return float(v)


def shape(kind, attrs):
    a = dict(re.findall(r"(\w+):`([^`]*)`", attrs))
    if kind == "path":
        # A path's first move is absolute even when written "m"; joined to
        # the shape before it, it would turn relative.
        # Pairs after "m" are relative lines, so they get an explicit "l".
        m = re.match(r"m\s*(-?[\d.]+)[\s,]*(-?[\d.]+)\s*(.*)", a["d"].strip(), re.S)
        if not m:
            return a["d"]
        rest = m.group(3)
        if rest and (rest[0].isdigit() or rest[0] in "-."):
            rest = "l" + rest
        return f"M{m.group(1)} {m.group(2)}{rest}"
    if kind == "line":
        return f"M{a['x1']} {a['y1']}L{a['x2']} {a['y2']}"
    if kind in ("polyline", "polygon"):
        pts = a["points"].replace(",", " ").split()
        d = "M" + " ".join(pts[:2]) + "".join(f"L{pts[i]} {pts[i+1]}" for i in range(2, len(pts), 2))
        return d + ("Z" if kind == "polygon" else "")
    if kind == "circle":
        cx, cy, r = num(a["cx"]), num(a["cy"]), num(a["r"])
        return f"M{cx-r:g} {cy:g}a{r:g} {r:g} 0 1 0 {2*r:g} 0a{r:g} {r:g} 0 1 0 {-2*r:g} 0Z"
    if kind == "rect":
        x, y, w, h = num(a.get("x", 0)), num(a.get("y", 0)), num(a["width"]), num(a["height"])
        rx = num(a.get("rx", a.get("ry", 0)))
        ry = num(a.get("ry", rx))
        if rx == 0:
            return f"M{x:g} {y:g}h{w:g}v{h:g}h{-w:g}Z"
        return (f"M{x+rx:g} {y:g}H{x+w-rx:g}A{rx:g} {ry:g} 0 0 1 {x+w:g} {y+ry:g}V{y+h-ry:g}"
                f"A{rx:g} {ry:g} 0 0 1 {x+w-rx:g} {y+h:g}H{x+rx:g}A{rx:g} {ry:g} 0 0 1 {x:g} {y+h-ry:g}"
                f"V{y+ry:g}A{rx:g} {ry:g} 0 0 1 {x+rx:g} {y:g}Z")
    raise SystemExit(f"unknown shape {kind}")


out = ["// Code generated by tools/lucide/gen.py from T3's web client. DO NOT EDIT.", "",
       "package ui", "", "// lucide is each icon's outline as SVG path data in a 24x24 box.",
       "var lucide = map[string]string{"]
for name in LUCIDE:
    m = re.search(r"`" + re.escape(name) + r"`,\[(\[`\w+`,\{[^}]*\}\](?:,\[`\w+`,\{[^}]*\}\])*)\]", bundle)
    if not m:
        raise SystemExit(f"no icon {name}")
    d = "".join(shape(k, at) for k, at in re.findall(r"\[`(\w+)`,\{([^}]*)\}\]", m.group(1)))
    out.append(f'\t"{name}": `{d}`,')
out.append("}")
out.append("")
print("\n".join(out))
